// Generates src/opl/dbopl_tables.h: DBOPL's wave, multiplier, KSL and tremolo tables as const arrays,
// so the firmware keeps them in flash instead of computing them into internal RAM at start.
//
//   g++ -O2 -I src/opl -o /tmp/gen_opl_tables tools/gen_opl_tables.cpp && /tmp/gen_opl_tables > src/opl/dbopl_tables.h
//
// Only needed after changing how dbopl.cpp builds these tables; the header is checked in.

#define DBOPL_GENERATE_TABLES
#include "../src/opl/dbopl.cpp"

#include <stdio.h>

template <typename T>
static void dump(char const * decl, T const * t, int n)
{
  printf("static const %s = {\n", decl);
  for (int i = 0; i < n; ++i)
    printf("%s%d,%s", i % 16 ? " " : "  ", (int) t[i], i % 16 == 15 || i == n - 1 ? "\n" : "");
  printf("};\n\n");
}

int main()
{
  DBOPL::InitTables();
  printf("// Generated by tools/gen_opl_tables.cpp from DBOPL's InitTables(). Do not edit.\n\n");
  printf("#pragma once\n\n");
  dump("int16_t WaveTable[ 8 * 512 ]", DBOPL::WaveTable, 8 * 512);
  dump("uint16_t MulTable[ 384 ]", DBOPL::MulTable, 384);
  dump("uint8_t KslTable[ 8 * 16 ]", DBOPL::KslTable, 8 * 16);
  dump("uint8_t TremoloTable[ TREMOLO_TABLE ]", DBOPL::TremoloTable, TREMOLO_TABLE);
  return 0;
}
